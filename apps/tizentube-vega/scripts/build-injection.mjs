#!/usr/bin/env node
/*
 * Generates src/injection/injectionBundle.generated.ts from:
 *   - src/injection/prelude.js    (platform shim, runs first)
 *   - src/injection/userScript.js (vendored TizenTube userscript build output)
 *
 * The result is a plain ES module exporting the concatenated source as a
 * string, which App.tsx passes to the WebView's
 * `injectedJavaScriptBeforeContentLoaded` prop. A string module is used
 * (rather than requiring raw JS through Metro) so the bundle works with any
 * Metro configuration and survives minification untouched.
 *
 * Run automatically via `npm run build:injection`; invoked again by
 * `npm run build:app` so a stale bundle can never ship.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const pkg = JSON.parse(read('package.json'));
const ttMeta = JSON.parse(read('.tizentube.json'));

let prelude = read('src/injection/prelude.js');
const userScript = read('src/injection/userScript.js');

if (!userScript || userScript.length < 10000) {
  throw new Error('src/injection/userScript.js looks empty/invalid. Run scripts/update-tizentube.sh first.');
}

prelude = prelude
  .replaceAll('__APP_VERSION__', pkg.version)
  .replaceAll('__TIZENTUBE_VERSION__', ttMeta.version);

// IIFE-safe concatenation. The trailing `true;` satisfies
// react-native-webview's "eval result" warning for injectedJavaScript props.
const bundle = `${prelude}\n;\n${userScript}\n;true;`;

const out = `/*
 * AUTO-GENERATED FILE — do not edit.
 * Generated by scripts/build-injection.mjs from:
 *   TizenTube v${ttMeta.version} (commit ${ttMeta.commit})
 * Regenerate with: npm run build:injection
 */
export const APP_VERSION = ${JSON.stringify(pkg.version)};
export const TIZENTUBE_VERSION = ${JSON.stringify(ttMeta.version)};
export const TIZENTUBE_COMMIT = ${JSON.stringify(ttMeta.commit)};
export const INJECTION_JS = ${JSON.stringify(bundle)};
`;

writeFileSync(join(root, 'src/injection/injectionBundle.generated.ts'), out);
console.log(
  `Generated injection bundle: ${(bundle.length / 1024).toFixed(0)} KB ` +
  `(TizenTube v${ttMeta.version} @ ${ttMeta.commit.slice(0, 12)})`
);
